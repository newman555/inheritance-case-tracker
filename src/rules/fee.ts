import { RuleError } from './errors'

// ルール8。売却時の仲介手数料：法定上限額、消費税10%込み、円未満切り捨て。
//
//   価格 200万円以下          ：価格の 5%
//   価格 200万円超 400万円以下：価格の 4% ＋ 2万円
//   価格 400万円超            ：価格の 3% ＋ 6万円
//   最後に消費税 10% を加える
//
// 「＋2万円」「＋6万円」は速算式の調整額。法律どおり価格を3つに分けて計算した合計と同じになる：
//   200万円までの部分 × 5% ＋ 200万〜400万円の部分 × 4% ＋ 400万円を超える部分 × 3%
// 例：3,000万円 → 10万 ＋ 8万 ＋ 78万（2,600万 × 3%）= 96万円。速算式でも 90万 ＋ 6万 = 96万円
//               → ＋10% = 1,056,000円
//
// 意図的に対応していないもの：800万円以下の物件の特例（上限33万円、2024年7月〜）。
// README の「既知の簡略化」に記載。
export function brokerageFee(price: number): number {
  // 価格は1円以上の整数であること。
  if (!Number.isInteger(price) || price <= 0) {
    throw new RuleError('INVALID_PRICE', '金額は1円以上の整数で入力してください。', 400, 'amount')
  }

  // 0.05 や 1.1 のような小数を掛けると誤差が出ることがある（JavaScript では 100000 × 1.1 = 110000.00000000001）。
  // そのため、整数を掛けてから割り、Math.floor で円未満を切り捨てる。
  let base: number
  if (price <= 2_000_000) {
    base = Math.floor((price * 5) / 100)
  } else if (price <= 4_000_000) {
    base = Math.floor((price * 4) / 100) + 20_000
  } else {
    base = Math.floor((price * 3) / 100) + 60_000
  }

  // 消費税10%：上と同じ理由で、1.1 ではなく「× 11 ÷ 10」で計算する。
  return Math.floor((base * 11) / 10)
}
